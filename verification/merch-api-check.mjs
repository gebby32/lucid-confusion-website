import assert from 'node:assert/strict';
import { FourthwallStore, CART_KEY, available, money, priceRange } from '../merch-api.js';

const storage = () => {
  const values = new Map();
  return { getItem: k => values.get(k) || null, setItem: (k, v) => values.set(k, v), removeItem: k => values.delete(k) };
};
const reply = (body, status = 200) => ({ ok: status < 400, status, json: async () => body });
const calls = [];
const s = storage();
let phase = 'pagination';
const store = new FourthwallStore('test-only', { storage: s, fetcher: async (url, options) => {
  const path = new URL(url).pathname, page = new URL(url).searchParams.get('page');
  calls.push({ path, method: options.method, body: options.body && JSON.parse(options.body) });
  if (phase === 'pagination') return reply({ results: [{ id: page, access: { type: 'PUBLIC' } }], paging: { hasNextPage: page === '0' } });
  if (phase === 'offline') throw new Error('network');
  if (phase === 'expired') return reply({}, 404);
  if (phase === 'rate-limited') return reply({}, 429);
  if (path.endsWith('/add')) return reply({ id: 'cart-one', items: [{ variant: { id: 'real-variant' }, quantity: 2 }] });
  return reply({ id: 'cart-one', items: [] });
} });
assert.equal((await store.products()).length, 2, 'Follow every all-collection page');
assert.deepEqual(calls.map(c => c.path), ['/v1/collections/all/products', '/v1/collections/all/products']);
phase = 'cart';
await store.update('add', [{ variantId: 'real-variant', quantity: 2 }]);
assert.equal(s.getItem(CART_KEY), 'cart-one');
assert.deepEqual(calls.find(c => c.path === '/v1/carts').body, { currency: 'USD', items: [] }, 'Live API requires items even for an empty cart');
assert.deepEqual(calls.at(-1).body, { items: [{ variantId: 'real-variant', quantity: 2 }] });
await store.update('change', [{ variantId: 'real-variant', quantity: 3 }]);
assert(calls.at(-1).path.endsWith('/carts/cart-one/change'));
await store.update('remove', [{ variantId: 'real-variant', quantity: 3 }]);
assert(calls.at(-1).path.endsWith('/carts/cart-one/remove'));
assert.equal(calls.filter(c => c.path === '/v1/carts' && c.method === 'POST').length, 1, 'Reuse one cart');
phase = 'offline';
await assert.rejects(store.refreshCart());
assert.equal(s.getItem(CART_KEY), 'cart-one', 'Never discard a saved cart on network failure');
phase = 'rate-limited';
await assert.rejects(store.refreshCart(), /busy/);
assert.equal(s.getItem(CART_KEY), 'cart-one');
phase = 'expired';
assert.equal(await store.refreshCart(), null);
assert.equal(s.getItem(CART_KEY), null);
assert(store.expired);
phase = 'cart';
const first = store.update('add', [{ variantId: 'real-variant', quantity: 1 }]);
await assert.rejects(store.update('add', [{ variantId: 'real-variant', quantity: 1 }]), /already in progress/);
await first;
const product = { state: { type: 'AVAILABLE' } };
assert(available(product, { id: 'a', unitPrice: { value: 20 }, stock: { type: 'UNLIMITED' } }));
assert(!available(product, { id: 'a', unitPrice: { value: 20 }, stock: { type: 'LIMITED', inStock: 0 } }));
assert(!available({ state: { type: 'SOLD_OUT' } }, { id: 'a', unitPrice: { value: 20 }, stock: { type: 'UNLIMITED' } }));
assert.equal(money(undefined), 'Price unavailable');
assert.equal(priceRange({ variants: [] }), 'Price unavailable');
console.log('PASS: pagination, real variant payload shape, one persistent cart, edits/removal, expired cart, offline/429 preservation, duplicate guard, availability and missing prices.');
